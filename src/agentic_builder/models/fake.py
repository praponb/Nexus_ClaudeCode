"""Deterministic, offline model double used for ``MODEL_PROVIDER=fake``.

Lets the orchestrator's own test suite (and ``--dry-run`` smoke checks)
exercise a full 3-cycle run with zero network access, per the spec's
"Permit a test double or fake model for orchestrator unit tests so CI does
not require paid API access" requirement.

Follows the exact same model<->tool protocol a real LLM would: on the first
turn it emits a ``function_call`` to its role's write tool; once ADK has
executed that tool and appended the ``function_response`` back into the
conversation, the next turn emits a final text summary. This means the
*real* tool safety code (path checks, ownership enforcement, atomic writes)
runs end-to-end in fake-model tests, not just mocked text.
"""

from __future__ import annotations

import json
import re
from collections.abc import AsyncGenerator

from google.adk.models import BaseLlm, LlmRequest, LlmResponse
from google.genai import types

_CYCLE_RE = re.compile(r"Cycle:\s*(\d+)")
_PHASE_RE = re.compile(r"Phase:\s*(\w+)")


def _latest_user_text(llm_request: LlmRequest) -> str:
    """Text of the most recent genuine user turn (not a tool function_response).

    Sessions persist conversation history across cycles within a role, so
    scanning the *entire* history for "Cycle: N" would always match the
    first cycle's text. Only the latest turn reflects what this invocation
    is actually about.
    """
    for content in reversed(llm_request.contents):
        if content.role != "user":
            continue
        texts = [part.text for part in (content.parts or []) if part.text]
        if texts:
            return "\n".join(texts)
    return ""


def _has_pending_function_response(llm_request: LlmRequest) -> bool:
    if not llm_request.contents:
        return False
    last = llm_request.contents[-1]
    return any(part.function_response is not None for part in (last.parts or []))


def _role_from_model(model: str) -> str:
    _, _, role = model.partition(":")
    return role or model


def _build_tool_call(role: str, phase: str, cycle: int) -> tuple[str, dict[str, str]]:
    """Return (tool_name, kwargs) for this role/phase/cycle."""
    if role == "team_lead":
        design_markdown = (
            f"# Detail Design Specification\n\n"
            f"## Revision (cycle {cycle})\n\n"
            f"Generated by the fake offline model for cycle {cycle}. "
            "Goals, scope, requirements, and architecture sections would be "
            "populated here by a real model run.\n"
        )
        cycle_plan_markdown = (
            f"# Cycle {cycle} Plan\n\nFrontend/backend/QA work items for cycle {cycle}.\n"
        )
        requirements = [
            {
                "req_id": "REQ-1",
                "description": "Fake requirement exercised by the offline test double.",
                "source_file": "specification.md",
                "status": "designed" if cycle == 1 else "implemented",
                "design_ref": f"cycle-{cycle}",
                "implementing_files": []
                if cycle == 1
                else ["frontend/README.md", "backend/README.md"],
                "test_ids": [] if cycle == 1 else [f"TC-{cycle}-001"],
            }
        ]
        return "publish_design_and_plan", {
            "design_markdown": design_markdown,
            "cycle_plan_markdown": cycle_plan_markdown,
            "requirements_json": json.dumps(requirements),
        }

    if role == "frontend":
        files = {"frontend/README.md": f"# Frontend (cycle {cycle})\n\nGenerated by fake model.\n"}
        summary = (
            f"# Frontend Cycle {cycle} Summary\n\n"
            f"Changed files: {list(files)}\nCommands run: none (fake model)\n"
        )
        return "write_frontend_files", {
            "files_json": json.dumps(files),
            "summary_markdown": summary,
        }

    if role == "backend":
        files = {"backend/README.md": f"# Backend (cycle {cycle})\n\nGenerated by fake model.\n"}
        summary = (
            f"# Backend Cycle {cycle} Summary\n\n"
            f"Changed files: {list(files)}\nCommands run: none (fake model)\n"
        )
        return "write_backend_files", {
            "files_json": json.dumps(files),
            "summary_markdown": summary,
        }

    if role == "qa":
        if phase == "execute":
            results = [
                {
                    "test_id": f"TC-{cycle}-001",
                    "status": "PASSED",
                    "actual_result": "Fake execution completed as expected.",
                    "evidence_path": f"runs/cycle-{cycle}/qa-execution-report.md",
                }
            ]
            report = (
                f"# QA Execution Report (cycle {cycle})\n\n1 test executed by the fake model.\n"
            )
            return "write_qa_execution_report", {
                "execution_report_markdown": report,
                "results_json": json.dumps(results),
                "defects_json": "[]",
            }
        files = {
            "testcase/TC-" + f"{cycle}-001.md": (
                f"# TC-{cycle}-001\n\nRequirement: REQ-1\nStatus: NOT_RUN\n"
                "Generated by fake model for offline testing.\n"
            )
        }
        summary = f"# QA Test Design Cycle {cycle} Summary\n\nTest cases authored: {list(files)}\n"
        return "write_testcase_files", {
            "files_json": json.dumps(files),
            "summary_markdown": summary,
        }

    raise ValueError(f"FakeLlm has no protocol for role {role!r}")


class FakeLlm(BaseLlm):
    """Deterministic, network-free stand-in for a real LLM.

    ``model`` is expected to look like ``"fake:<role>"`` (e.g.
    ``"fake:team_lead"``), set by ``models.provider.build_llm``.
    """

    async def generate_content_async(
        self, llm_request: LlmRequest, stream: bool = False
    ) -> AsyncGenerator[LlmResponse, None]:
        role = _role_from_model(self.model)
        context_text = _latest_user_text(llm_request)
        cycle_match = _CYCLE_RE.search(context_text)
        cycle = int(cycle_match.group(1)) if cycle_match else 1
        phase_match = _PHASE_RE.search(context_text)
        phase = phase_match.group(1) if phase_match else "design"

        if _has_pending_function_response(llm_request):
            summary_text = (
                f"[fake:{role}] Completed cycle {cycle} ({phase} phase). "
                "Tool call executed successfully; see the written summary file for details."
            )
            yield LlmResponse(
                content=types.Content(role="model", parts=[types.Part(text=summary_text)]),
                partial=False,
                turn_complete=True,
            )
            return

        tool_name, kwargs = _build_tool_call(role, phase, cycle)
        yield LlmResponse(
            content=types.Content(
                role="model",
                parts=[types.Part(function_call=types.FunctionCall(name=tool_name, args=kwargs))],
            ),
            partial=False,
            turn_complete=True,
        )
