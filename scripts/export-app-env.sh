#!/usr/bin/env bash
# Extract the Asset Inventory app's configuration from the repo-root .env,
# leaving the agentic_builder orchestrator's secrets behind.
#
# Usage:  ./scripts/export-app-env.sh [OUTPUT]        (default: app.env)
# Then:   scp app.env prapon@192.168.1.49:~/inventory/.env && rm app.env
#
# WHY THIS EXISTS: the root .env is a merged file. It carries the orchestrator's
# paid API keys (MODEL_API_KEY, GEMINI_API_KEY) alongside the web app's Django
# settings. Copying it wholesale to a web server would put LLM billing
# credentials on a host that has no use for them and a larger attack surface
# than this laptop -- so the copy is an allowlist, not an exclusion list. A key
# that is not named below does not travel, including any added later.
set -euo pipefail

cd "$(dirname "$0")/.."

SRC=".env"
DEST="${1:-app.env}"

if [ ! -f "$SRC" ]; then
  echo "ERROR: $SRC not found. Run from a checkout with a configured .env." >&2
  exit 1
fi

# Everything the Django/Nuxt stack reads. Verified against
# backend/config/settings/*.py and compose.yaml -- note SECRET_KEY and REDIS_URL
# are real fallbacks (base.py:34, base.py:290), not leftovers.
APP_KEYS=(
  APP_ENV APP_BASE_URL
  DJANGO_SETTINGS_MODULE DJANGO_SECRET_KEY SECRET_KEY DJANGO_DEBUG
  DJANGO_ALLOWED_HOSTS DJANGO_CSRF_TRUSTED_ORIGINS DJANGO_CORS_ALLOWED_ORIGINS
  CORS_ALLOWED_ORIGINS
  POSTGRES_DB POSTGRES_USER POSTGRES_PASSWORD POSTGRES_HOST POSTGRES_PORT
  POSTGRES_SSLMODE
  REDIS_URL CACHE_URL CELERY_BROKER_URL CELERY_RESULT_BACKEND
  CELERY_TASK_ALWAYS_EAGER
  LOCAL_AUTH_ENABLED LOCAL_AUTH_ALLOW_IN_PRODUCTION
  TRUSTED_CLIENT_IP_HEADER SESSION_IDLE_SECONDS
  BACKEND_BUILD_TARGET BACKEND_PORT FRONTEND_PORT
  MEDIA_ROOT ATTACHMENT_MAX_BYTES ATTACHMENT_ALLOWED_EXTENSIONS
  NUXT_PUBLIC_API_BASE_URL
  LOG_LEVEL SEED_DEMO_PASSWORD
)

# Create the file empty and locked down BEFORE writing any secret into it, so
# there is no window where it exists world-readable.
umask 077
: > "$DEST"

{
  echo "# Asset Inventory app configuration."
  echo "# Generated by scripts/export-app-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo "# Contains secrets. Mode 600. Never commit."
  echo
} >> "$DEST"

CARRIED=0
MISSING=()
for key in "${APP_KEYS[@]}"; do
  # Match the last assignment of the key, ignoring commented lines. Values are
  # copied verbatim and never echoed to the terminal.
  line="$(grep -E "^${key}=" "$SRC" | tail -n 1 || true)"
  if [ -n "$line" ]; then
    printf '%s\n' "$line" >> "$DEST"
    CARRIED=$((CARRIED + 1))
  else
    MISSING+=("$key")
  fi
done

chmod 600 "$DEST"

echo "==> Wrote $DEST (mode 600) with ${CARRIED} of ${#APP_KEYS[@]} app keys."
if [ ${#MISSING[@]} -gt 0 ]; then
  echo "==> Not present in $SRC (fine if the default suits you): ${MISSING[*]}"
fi

# Name what was deliberately left behind, so a reviewer can see the allowlist
# did its job without anyone opening the file.
echo "==> Left behind (not read by the web app):"
grep -oE '^[A-Z_]+=' "$SRC" | tr -d '=' | sort -u > /tmp/.appenv-all.$$
printf '%s\n' "${APP_KEYS[@]}" | sort -u > /tmp/.appenv-keep.$$
comm -23 /tmp/.appenv-all.$$ /tmp/.appenv-keep.$$ | sed 's/^/      /'
rm -f /tmp/.appenv-all.$$ /tmp/.appenv-keep.$$

cat <<'EOF'

==> Next:
      scp app.env prapon@192.168.1.49:~/inventory/.env
      rm app.env          # do not leave a second copy of the secrets lying around
    Then on the server, confirm the production settings module is selected:
      grep -E "^(APP_ENV|DJANGO_SETTINGS_MODULE|BACKEND_BUILD_TARGET)=" ~/inventory/.env
EOF
